from reportlab.lib.pagesizes import letter, landscape
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors


class AuditReportGenerator:
    @staticmethod
    def generate_pdf_report(filename: str, document_name: str, final_state: dict) -> str:
        doc = SimpleDocTemplate(
            filename,
            pagesize=landscape(letter),
            rightMargin=30,
            leftMargin=30,
            topMargin=30,
            bottomMargin=30,
        )
        story = []
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#0F172A"),
            spaceAfter=8,
        )
        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["BodyText"],
            fontSize=9.5,
            leading=13,
            textColor=colors.HexColor("#334155"),
            spaceAfter=4,
        )
        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["BodyText"],
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor("#1E293B"),
        )
        error_style = ParagraphStyle(
            "ErrorBanner",
            parent=styles["BodyText"],
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#991B1B"),
            backColor=colors.HexColor("#FEE2E2"),
            borderPadding=12,
        )

        story.append(Paragraph("VERITAS COMPLIANCE — ENTERPRISE AUDIT REPORT", title_style))
        story.append(Paragraph(f"<b>Document Audited:</b> {document_name}", meta_style))
        story.append(Spacer(1, 6))

        ai_error = final_state.get("ai_error")
        if ai_error:
            banner_text = (
                "<b>⚠️ AI ANALYSIS UNAVAILABLE — this report was NOT generated by the compliance AI.</b><br/>"
                "No findings below should be used for any decision. Retry once service is restored.<br/><br/>"
                f"<b>Diagnostic Error:</b> {ai_error}"
            )
            story.append(Paragraph(banner_text, error_style))
            doc.build(story)
            return filename

        findings = final_state.get("audit_report", {}).get("findings", [])
        model_used = final_state.get("model_used", "Gemini")
        citation_status = final_state.get("citation_review_status", "Not verified")

        compliant_cnt = sum(1 for f in findings if f.get("result", "").lower() == "compliant")
        non_compliant_cnt = sum(1 for f in findings if f.get("result", "").lower() == "non-compliant")
        undetermined_cnt = len(findings) - compliant_cnt - non_compliant_cnt
        total_cnt = len(findings)

        story.append(Paragraph(f"<b>Analysis method:</b> {model_used} (multi-agent LangGraph pipeline) [PASSED]", meta_style))
        story.append(Paragraph(f"<b>Citation review:</b> {citation_status}", meta_style))
        story.append(
            Paragraph(
                f"<b>Rules reviewed:</b> {total_cnt} | <b>Compliant:</b> {compliant_cnt} | "
                f"<b>Non-compliant:</b> {non_compliant_cnt} | <b>Undetermined:</b> {undetermined_cnt} "
                f"<i>({total_cnt} = {compliant_cnt} + {non_compliant_cnt} + {undetermined_cnt} — counts reconciled)</i>",
                meta_style,
            )
        )
        story.append(Spacer(1, 12))

        table_data = [[
            "Compliance rule",
            "Result",
            "Priority",
            "Citation (exact contract text + page)",
            "Reasoning",
            "Next step",
        ]]

        for item in findings:
            res_val = item.get("result", "Undetermined")
            color_hex = (
                "#15803D"
                if res_val.lower() == "compliant"
                else ("#B91C1C" if res_val.lower() == "non-compliant" else "#B45309")
            )
            table_data.append([
                Paragraph(item.get("rule", ""), body_style),
                Paragraph(f"<font color='{color_hex}'><b>{res_val}</b></font>", body_style),
                Paragraph(item.get("priority", "Medium"), body_style),
                Paragraph(f"<i>{item.get('citation', '')}</i>", body_style),
                Paragraph(item.get("reasoning", ""), body_style),
                Paragraph(item.get("next_step", ""), body_style),
            ])

        col_widths = [120, 75, 55, 192, 180, 110]
        results_table = Table(table_data, colWidths=col_widths, repeatRows=1)
        results_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E293B")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, 0), 9),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
                ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#F8FAFC")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 1), (-1, -1), 7),
                ("BOTTOMPADDING", (0, 1), (-1, -1), 7),
            ])
        )

        story.append(results_table)
        doc.build(story)
        return filename
